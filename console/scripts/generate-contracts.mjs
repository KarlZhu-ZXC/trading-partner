import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { spawnSync } from "node:child_process";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { compile } from "json-schema-to-typescript";

const consoleRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const projectRoot = resolve(consoleRoot, "..");
const outputPath = resolve(consoleRoot, "app/lib/generated/contracts.ts");
const manifestPath = resolve(consoleRoot, "app/lib/generated/contracts.manifest.json");
const check = process.argv.includes("--check");

const exported = spawnSync(
  "uv",
  ["run", "python", "scripts/export_contract_schemas.py"],
  { cwd: projectRoot, encoding: "utf8" },
);
if (exported.status !== 0) {
  process.stderr.write(exported.stderr || "Contract schema export failed.\n");
  process.exit(exported.status || 1);
}
const schemas = JSON.parse(exported.stdout);
const sections = [];
for (const [name, schema] of Object.entries(schemas)) {
  const generated = await compile({ ...schema, title: name }, name, {
    bannerComment: "",
    format: true,
    style: { singleQuote: false, semi: true, tabWidth: 2, trailingComma: "all" },
    unreachableDefinitions: true,
  });
  const namespace = `${name}Types`;
  const indented = generated.trim().split("\n").map((line) => (
    line ? `  ${line}` : ""
  )).join("\n");
  sections.push(
    `export namespace ${namespace} {\n${indented}\n}\n\n`
    + `export type ${name} = ${namespace}.${name};`,
  );
}
const content = `${[
  "/* AUTO-GENERATED by console/scripts/generate-contracts.mjs. DO NOT EDIT. */",
  "/* eslint-disable @typescript-eslint/no-namespace */",
  ...sections.map((value) => value.trim()),
  "",
].join("\n\n").trimEnd()}\n`;
const canonical = exported.stdout.trim();
const manifest = `${JSON.stringify({
  generator: "pydantic-json-schema+json-schema-to-typescript",
  schema_sha256: createHash("sha256").update(canonical).digest("hex"),
  type_count: Object.keys(schemas).length,
}, null, 2)}\n`;

if (check) {
  const [existing, existingManifest] = await Promise.all([
    readFile(outputPath, "utf8"),
    readFile(manifestPath, "utf8"),
  ]);
  if (existing !== content || existingManifest !== manifest) {
    process.stderr.write("Generated Agent contracts are stale. Run npm run generate:contracts.\n");
    process.exit(1);
  }
} else {
  await mkdir(dirname(outputPath), { recursive: true });
  await Promise.all([
    writeFile(outputPath, content),
    writeFile(manifestPath, manifest),
  ]);
}
